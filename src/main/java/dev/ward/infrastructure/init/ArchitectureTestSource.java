package dev.ward.infrastructure.init;

import dev.ward.domain.init.QualityPreset;
import java.util.ArrayList;
import java.util.List;
import java.util.SortedSet;
import java.util.TreeSet;

/**
 * Renders the generated ArchUnit test already formatted the way google-java-format lays it out, so
 * a {@code format} gate passes right after init. Each statement uses the first layout that fits in
 * {@value #WIDTH} columns: one line, a break after the operator, or one call per line.
 */
final class ArchitectureTestSource {
  private static final int WIDTH = 100;
  private static final int IMPORT_LENGTH = 80;
  private static final String MEMBER_INDENT = "  ";
  private static final String CONTINUATION = "      ";
  private static final String CHAIN_INDENT = "          ";
  private static final String NO_CLASSES =
      "static com.tngtech.archunit.lang.syntax.ArchRuleDefinition.noClasses";
  private static final String SLICES =
      "static com.tngtech.archunit.library.dependencies.SlicesRuleDefinition.slices";
  private static final String CODING_RULES = "com.tngtech.archunit.library.GeneralCodingRules";

  private ArchitectureTestSource() {}

  static String render(
      final String basePackage,
      final String architecture,
      final QualityPreset.ArchitectureExtras extras) {
    final SortedSet<String> imports =
        new TreeSet<>(
            List.of(
                NO_CLASSES,
                "com.tngtech.archunit.core.importer.ImportOption",
                "com.tngtech.archunit.junit.AnalyzeClasses",
                "com.tngtech.archunit.junit.ArchTest",
                "com.tngtech.archunit.lang.ArchRule"));
    final List<String> members = new ArrayList<>();
    members.add(rule("architecture", layerRule(architecture)));
    if (extras.cycles()) {
      imports.add(SLICES);
      members.add(
          rule(
              "noCycles",
              List.of(
                  "slices()",
                  ".matching(\"" + basePackage + ".(*)..\")",
                  ".should()",
                  ".beFreeOfCycles()")));
    }
    if (extras.noFieldInjection()) {
      imports.add(CODING_RULES);
      members.add(
          rule(
              "noFieldInjection",
              List.of("GeneralCodingRules.NO_CLASSES_SHOULD_USE_FIELD_INJECTION")));
    }
    if (extras.noStandardStreams()) {
      imports.add(CODING_RULES);
      members.add(
          rule(
              "noStandardStreams",
              List.of("GeneralCodingRules.NO_CLASSES_SHOULD_ACCESS_STANDARD_STREAMS")));
    }
    return "package "
        + basePackage
        + ";\n\n"
        + importBlock(imports)
        + "\n// Generated by Ward for the "
        + architecture
        + " architecture.\n"
        + annotation(basePackage)
        + "class ArchitectureTest {\n"
        + String.join("\n", members)
        + "}\n";
  }

  /** Static imports first, then a blank line, then the others; each group sorted. */
  private static String importBlock(final SortedSet<String> imports) {
    final StringBuilder block = new StringBuilder(IMPORT_LENGTH * imports.size());
    imports.stream()
        .filter(name -> name.startsWith("static "))
        .forEach(name -> block.append("import ").append(name).append(";\n"));
    block.append('\n');
    imports.stream()
        .filter(name -> !name.startsWith("static "))
        .forEach(name -> block.append("import ").append(name).append(";\n"));
    return block.toString();
  }

  private static String annotation(final String basePackage) {
    final String packages = "packages = \"" + basePackage + "\"";
    final String options = "importOptions = ImportOption.DoNotIncludeTests.class";
    final String oneLine = "@AnalyzeClasses(" + packages + ", " + options + ")";
    if (oneLine.length() <= WIDTH) {
      return oneLine + "\n";
    }
    return "@AnalyzeClasses(\n    " + packages + ",\n    " + options + ")\n";
  }

  private static List<String> layerRule(final String architecture) {
    return switch (architecture) {
      case "hexagonal" ->
          layerRule(
              "\"..domain..\", \"..application..\"", "\"..adapter..\", \"..infrastructure..\"");
      case "clean" ->
          layerRule(
              "\"..domain..\", \"..core..\"",
              "\"..controller..\", \"..adapter..\", \"..infrastructure..\"");
      default -> layerRule("\"..controller..\"", "\"..repository..\"");
    };
  }

  /**
   * Layer packages may not exist yet in a new project, so the rule passes until classes appear in
   * them instead of failing with "failed to check any classes".
   */
  private static List<String> layerRule(final String inner, final String outer) {
    return List.of(
        "noClasses()",
        ".that()",
        ".resideInAnyPackage(" + inner + ")",
        ".should()",
        ".dependOnClassesThat()",
        ".resideInAnyPackage(" + outer + ")",
        ".allowEmptyShould(true)");
  }

  /** Like google-java-format, keeps {@code @ArchTest} on the field's line when all of it fits. */
  private static String rule(final String name, final List<String> chain) {
    final String declaration = MEMBER_INDENT + "static final ArchRule " + name + " =";
    final String expression = String.join("", chain) + ";";
    final String oneLine = declaration + " " + expression;
    final String annotated = MEMBER_INDENT + "@ArchTest " + oneLine.strip();
    if (annotated.length() <= WIDTH) {
      return annotated + "\n";
    }
    final String body;
    if (oneLine.length() <= WIDTH) {
      body = oneLine;
    } else if (CONTINUATION.length() + expression.length() <= WIDTH) {
      body = declaration + "\n" + CONTINUATION + expression;
    } else {
      body =
          declaration
              + "\n"
              + CONTINUATION
              + chain.getFirst()
              + chain.stream()
                  .skip(1)
                  .map(call -> "\n" + CHAIN_INDENT + call)
                  .reduce("", String::concat)
              + ";";
    }
    return MEMBER_INDENT + "@ArchTest\n" + body + "\n";
  }
}
